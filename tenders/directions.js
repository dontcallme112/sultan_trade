export const DIRECTION_IDS = DIRECTIONS.map(d => d.id);

// Возвращает { ids: [...], hits: { id: n } }. «Прочее» ставится, только если ничего не найдено.
export function classify(text) {
  const t = String(text || '').toLowerCase();
  const hits = {};
  for (const d of DIRECTIONS) {
    if (!d.words.length) continue;
    const n = d.words.filter(w => t.includes(w)).length;
    if (n) hits[d.id] = n;
  }
  const ids = Object.keys(hits).sort((a, b) => hits[b] - hits[a]);
  return { ids: ids.length ? ids : ['other'], hits };
}
